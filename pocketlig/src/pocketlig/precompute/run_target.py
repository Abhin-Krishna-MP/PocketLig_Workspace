"""Precompute everything for ONE target into artifacts/<target_id>/ (resumable; every step skips if its output exists).

Steps: prepare -> sample -> export -> eval -> electro -> manifest.
  python -m pocketlig.precompute.run_target 1abc --ligand-resname XYZ --chain A --out artifacts/1abc \
      --targetdiff-dir ../targetdiff --config configs/sampling.yml --num-samples 100 [--gnn runs/gnn_s0/best.pt]
`sample` and `electro` shell out to GPU/solver tools and are NOT exercised in the build sandbox.
"""
from __future__ import annotations

import argparse
import glob
import json
import platform
import shutil
import subprocess
import sys
import time
import urllib.request
from datetime import date
from pathlib import Path

import numpy as np

from ..data.pocket import clean_protein, extract_pocket_residues, load_structure, write_pocket
from ..generation.traj_io import npz_to_frontend_json
from .electrostatics import run_apbs, run_pdb2pqr


def fetch_pdb(pdb_id: str, dest: Path) -> None:
    url = f"https://files.rcsb.org/download/{pdb_id.upper()}.pdb"
    with urllib.request.urlopen(url, timeout=60) as r:
        dest.write_bytes(r.read())


def ligand_coords_from_pdb(pdb_path: Path, resname: str, chain: str | None) -> np.ndarray:
    xyz = []
    for line in pdb_path.read_text().splitlines():
        if line.startswith("HETATM") and line[17:20].strip() == resname and (chain is None or line[21] == chain):
            if line[76:78].strip().upper() != "H":
                xyz.append([float(line[30:38]), float(line[38:46]), float(line[46:54])])
    if not xyz:
        raise ValueError(f"no HETATM atoms for residue {resname} chain {chain}")
    return np.asarray(xyz)


def step_prepare(pdb_id: str, resname: str, chain: str | None, out: Path, cutoff: float) -> dict:
    if (out / "pocket.pdb").exists() and (out / "protein.pdb").exists():
        return {"skipped": True}
    raw = out / "raw.pdb"
    if not raw.exists():
        fetch_pdb(pdb_id, raw)
    xyz = ligand_coords_from_pdb(raw, resname, chain)
    log = clean_protein(raw, out / "protein.pdb")
    st = load_structure(out / "protein.pdb")
    residues = extract_pocket_residues(st, xyz, cutoff)
    write_pocket(st, residues, out / "pocket.pdb")
    log.update({"pocket_residues": len(residues), "pocket_cutoff_A": cutoff, "reference_ligand": resname})
    return log


def step_sample(out: Path, a) -> dict:
    cmd = [sys.executable, str(Path(__file__).resolve().parents[3] / "scripts" / "targetdiff_sample_pocket.py"),
           a.config, "--pdb_path", str((out / "pocket.pdb").resolve()), "--out_dir", str((out / "trajectories").resolve()),
           "--num_samples", str(a.num_samples), "--chunk", str(a.chunk), "--n_frames", str(a.n_frames),
           "--device", a.device]
    env_path = str(Path(__file__).resolve().parents[2])
    subprocess.run(cmd, check=True, cwd=a.targetdiff_dir, env={**__import__("os").environ, "PYTHONPATH": f"{env_path}:."})
    return {"cmd": cmd}


def step_export(out: Path) -> dict:
    n = 0
    for npz in sorted((out / "trajectories").glob("mol_*/frames.npz")):
        target = npz.with_name("frames.json")
        if not target.exists():
            npz_to_frontend_json(npz, target)
        n += 1
    return {"molecules_exported": n}


def step_eval(out: Path, a) -> dict:
    from ..eval.run_eval import evaluate_folder

    res = evaluate_folder(str(out / "trajectories"), str(out / "pocket.pdb"), a.receptor_pdbqt, a.gnn)
    (out / "metrics.json").write_text(json.dumps(res, indent=2))
    return {"n_valid": res["n_valid"], "n_files": res["n_files"]}


def step_electro(out: Path, ff: str, ph: float) -> dict:
    if (out / "surface_potential.dx").exists():
        return {"skipped": True}
    work = (out / "apbs_work").resolve()
    work.mkdir(exist_ok=True)
    prot = (out / "protein.pdb").resolve()
    info = run_pdb2pqr(prot, "protein.pqr", "apbs.in", ff=ff, ph=ph, cwd=work)
    run_apbs("apbs.in", work)
    dx = sorted(glob.glob(str(work / "*.dx")))
    if not dx:
        raise RuntimeError("APBS produced no .dx file; inspect apbs_work/")
    shutil.copyfile(dx[0], out / "surface_potential.dx")
    info.update({"apbs_input": "apbs.in (generated by pdb2pqr; see apbs_work/)", "dx_source": Path(dx[0]).name})
    return info


def versions() -> dict:
    v = {"python": platform.python_version()}
    for mod in ("torch", "rdkit", "Bio", "numpy", "torch_geometric"):
        try:
            v[mod] = __import__(mod).__version__ if mod != "rdkit" else __import__("rdkit").__version__
        except Exception:
            v[mod] = None
    return v


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("pdb_id")
    ap.add_argument("--ligand-resname", required=True, help="3-letter HETATM residue name of the co-crystal ligand")
    ap.add_argument("--chain")
    ap.add_argument("--out", required=True)
    ap.add_argument("--steps", default="prepare,sample,export,eval,electro")
    ap.add_argument("--pocket-cutoff", type=float, default=10.0)
    ap.add_argument("--targetdiff-dir", default="../targetdiff")
    ap.add_argument("--config", default="configs/sampling.yml")
    ap.add_argument("--num-samples", dest="num_samples", type=int, default=100)
    ap.add_argument("--chunk", type=int, default=10)
    ap.add_argument("--n-frames", dest="n_frames", type=int, default=50)
    ap.add_argument("--device", default="cuda:0")
    ap.add_argument("--receptor-pdbqt", dest="receptor_pdbqt")
    ap.add_argument("--gnn")
    ap.add_argument("--ff", default="AMBER")
    ap.add_argument("--ph", type=float, default=7.0)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    manifest_path = out / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {"steps": {}}
    manifest.update({"target_id": a.pdb_id.lower(), "source": f"RCSB PDB {a.pdb_id.upper()}", "date": date.today().isoformat(),
                     "versions": versions(), "electrostatics": {"force_field": a.ff, "ph": a.ph}})
    for step in a.steps.split(","):
        t0 = time.time()
        if step == "prepare":
            info = step_prepare(a.pdb_id, a.ligand_resname, a.chain, out, a.pocket_cutoff)
        elif step == "sample":
            info = step_sample(out, a)
        elif step == "export":
            info = step_export(out)
        elif step == "eval":
            info = step_eval(out, a)
        elif step == "electro":
            info = step_electro(out, a.ff, a.ph)
        else:
            raise SystemExit(f"unknown step {step}")
        manifest["steps"][step] = {**info, "seconds": round(time.time() - t0, 1)}
        meta = out / "trajectories" / "sampling_meta.json"
        if meta.exists():
            m = json.loads(meta.read_text())
            manifest["generator"] = {k: m[k] for k in ("checkpoint", "checkpoint_sha256", "num_steps", "seed") if k in m}
        manifest_path.write_text(json.dumps(manifest, indent=2, default=str))
        print(f"[{step}] done in {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
